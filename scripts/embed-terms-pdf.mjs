#!/usr/bin/env node
/**
 * Embed a printed copy of the Knowledge Centre terms (Coaching Terms + Booking
 * and Refund Policy, one PDF) for one terms version, so the payment email can
 * attach exactly the terms a customer agreed to.
 *
 *   node scripts/embed-terms-pdf.mjs <terms-version> <path-to.pdf>
 *
 * Writes src/legal/terms-<version>.generated.ts. Then add one line for it to
 * src/legal/terms-pdfs.ts. The PDF is embedded as code rather than read from
 * disk at send time, so it ships with the server build and cannot go missing.
 *
 * How the PDF is made: build zaaheen.com, serve it, and print
 * /knowledge-centre/terms/ and /knowledge-centre/booking-and-refunds/ with
 * headless Chrome (--print-to-pdf --no-pdf-header-footer; the site's print
 * stylesheet gives A4 with the words only), then join them with pdfunite.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

/** The module text for one version. Refuses anything that is not a dated version and a PDF. */
export function termsPdfModule(version, bytes) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(version)) {
    throw new Error(`terms version must be YYYY-MM-DD, got "${version}"`);
  }
  if (bytes.subarray(0, 5).toString("latin1") !== "%PDF-") {
    throw new Error("the file is not a PDF");
  }
  return [
    `// Generated by scripts/embed-terms-pdf.mjs from the printed terms, version ${version}.`,
    "// Do not edit: print the terms again and rerun the script.",
    `export const TERMS_PDF_${version.replace(/-/g, "_")} =`,
    `  "${bytes.toString("base64")}";`,
    "",
  ].join("\n");
}

/** Write src/legal/terms-<version>.generated.ts under `root`; returns the path written. */
export function embedTermsPdf({ version, pdfPath, root }) {
  const out = join(root, "src", "legal", `terms-${version}.generated.ts`);
  writeFileSync(out, termsPdfModule(version, readFileSync(pdfPath)));
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const [version, pdfPath] = process.argv.slice(2);
  if (!version || !pdfPath) {
    console.error("usage: node scripts/embed-terms-pdf.mjs <YYYY-MM-DD> <path-to.pdf>");
    process.exit(1);
  }
  console.log(`wrote ${embedTermsPdf({ version, pdfPath, root: process.cwd() })}`);
}
